def tracked_paths(root: Path) -> list[str]:
    result = subprocess.run(["git", "ls-files", "-z"], cwd=root, check=True,
                            stdout=subprocess.PIPE)
    return sorted(set(result.stdout.decode("utf-8").rstrip("\0").split("\0")) - {""})


def safe_relative(name: str) -> str:
    path = PurePosixPath(name)
    if (not name or path.is_absolute() or ".." in path.parts or "\\" in name
            or ":" in name or str(path) != name):
        raise ValueError(f"unsafe repository path: {name!r}")
    return name


def xml(element: ET.Element) -> str:
    ET.indent(element, space="  ")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + f"<!-- {MARKER} -->\n" + ET.tostring(element, encoding="unicode") + "\n"


def component(name: str) -> tuple[ET.Element, ET.Element]:
    project = ET.Element("project", version="4")
    return project, ET.SubElement(project, "component", name=name)


def option(parent: ET.Element, name: str, value: str) -> None:
    ET.SubElement(parent, "option", name=name, value=value)


def source_model(root: Path, paths: list[str]) -> tuple[list[str], list[str]]:
    """Use manifests for Rust and tracked directories for the polyglot layout."""
    roots = {"."}
    cargo = []
    for name in paths:
        safe_relative(name)
        parts = PurePosixPath(name).parts
        if len(parts) > 1 and parts[0] in {"sdk", "docs", "website", "research", "examples", "tools"}:
            roots.add("/".join(parts[:2]) if parts[0] == "sdk" and len(parts) > 2 else parts[0])
        if parts[-1] != "Cargo.toml" or set(parts) & {"templates", "template", "fixtures", "testdata", "tests", "vendor"}:
            continue
        manifest = tomllib.loads((root / name).read_text(encoding="utf-8"))
        if "workspace" not in manifest:
            continue
        cargo.append(name)
        base = PurePosixPath(name).parent
        roots.add(str(base))
        excluded = [str(base / pattern) for pattern in manifest["workspace"].get("exclude", [])]
        for member in manifest["workspace"].get("members", []):
            candidate = str(base / member)
            safe_relative(candidate)
            # Cargo supports globbed members; resolve against tracked manifests,
            # not ignored output or a developer's unrelated directories.
            for path in paths:
                directory = str(PurePosixPath(path).parent)
                if (PurePosixPath("/" + path).match("/" + candidate + "/Cargo.toml")
                        and not any(PurePosixPath("/" + directory).match("/" + pattern) for pattern in excluded)):
                    roots.add(directory)
    if "Cargo.toml" not in cargo:
        raise ValueError("the root Cargo workspace is missing")
    # SDK READMEs belong to the root module, not a fake sdk/README.md module.
    return sorted(roots), sorted(cargo)


def module_name(path: str) -> str:
    # Delimiters avoid collisions between a/b-c and a-b/c.
    return "lsf" if path == "." else "lsf." + path.replace("/", ".")


def module_file(path: str) -> str:
    module = ET.Element("module", type="JAVA_MODULE" if path == "sdk/java-client" else "EMPTY_MODULE", version="4")
    manager = ET.SubElement(module, "component", name="NewModuleRootManager", **{"inherit-compiler-output": "true"})
    url = "file://$MODULE_DIR$/../.." + ("/" + path if path != "." else "")
    content = ET.SubElement(manager, "content", url=url)
    # Nested content roots already define module ownership. Excluding another
    # module's content root marks real sources as excluded (brown/orange folders)
    # in IDEA's Project view. Only caches and actual output belong in exclusions.
    for pattern in CACHE_NAMES:
        ET.SubElement(content, "excludePattern", pattern=pattern)
    if path == ".":
        for excluded in (".git", ".idea", "target", ".venv", ".zig-cache"):
            ET.SubElement(content, "excludeFolder", url=url + "/" + excluded)
    if path == "website":
        for excluded in ("build", "build-root", ".docusaurus", "playwright-report", "test-results"):
            ET.SubElement(content, "excludeFolder", url=url + "/" + excluded)
    if path.startswith("sdk/typescript-"):
        ET.SubElement(content, "excludeFolder", url=url + "/dist")
    if path.startswith("sdk/dotnet"):
        ET.SubElement(content, "excludePattern", pattern="obj")
        ET.SubElement(content, "excludePattern", pattern="bin")
    if path == "sdk/java-client":
        for source, test, generated in (("src/transport/java", False, False), ("src/example/java", False, False),
                                        ("build/generated/java", False, True), ("src/transportTest/java", True, False)):
            ET.SubElement(content, "sourceFolder", url=url + "/" + source,
                          isTestSource=str(test).lower(), **({"generated": "true"} if generated else {}))
        for excluded in ("build/classes", "build/test-classes", "build/deps"):
            ET.SubElement(content, "excludeFolder", url=url + "/" + excluded)
        ET.SubElement(manager, "orderEntry", type="inheritedJdk")
        entry = ET.SubElement(manager, "orderEntry", type="module-library")
        library = ET.SubElement(entry, "library", name="LSF Java client locked dependencies")
        jars = url + "/build/deps"
        ET.SubElement(ET.SubElement(library, "CLASSES"), "root", url=jars)
        ET.SubElement(library, "JAVADOC")
        ET.SubElement(library, "SOURCES")
        ET.SubElement(library, "jarDirectory", url=jars, recursive="false")
    ET.SubElement(manager, "orderEntry", type="sourceFolder", forTests="false")
    return xml(module)


def run_configuration(task: str, folder: str, *, windows: bool = False) -> str:
    project = ET.Element("component", name="ProjectRunConfigurationManager")
    platform = "Windows" if windows else "Bash"
    script = "intellij.cmd" if windows else "intellij.sh"
    text = f"cmd.exe /d /c tools\\intellij.cmd {task}" if windows else f"bash tools/intellij.sh {task}"
    config = ET.SubElement(project, "configuration", default="false", name=f"LSF - {task} ({platform})",
                           type="ShConfigurationType", folderName=f"LSF / {platform} / " + folder)
    # Script-text mode runs in the selected terminal: PowerShell/cmd on Windows,
    # Bash on POSIX. Never resolve a bare bash.exe in a native Windows task.
    for name, value in (("SCRIPT_TEXT", text), ("INDEPENDENT_SCRIPT_PATH", "true"),
                        ("SCRIPT_PATH", "$PROJECT_DIR$/tools/" + script), ("SCRIPT_OPTIONS", task),
                        ("INDEPENDENT_SCRIPT_WORKING_DIRECTORY", "true"),
                        ("SCRIPT_WORKING_DIRECTORY", "$PROJECT_DIR$"), ("INTERPRETER_PATH", ""),
                        ("INTERPRETER_OPTIONS", ""), ("EXECUTE_IN_TERMINAL", "true"),
                        ("EXECUTE_SCRIPT_FILE", "false")):
        option(config, name, value)
    ET.SubElement(config, "method", v="2")
    return xml(project)


def cargo_configuration(name: str, command: str) -> str:
    project = ET.Element("component", name="ProjectRunConfigurationManager")
    config = ET.SubElement(project, "configuration", default="false", name="LSF - " + name,
                           type="CargoCommandRunConfiguration", factoryName="Cargo Command", folderName="LSF / 70 Native debug")
    for key, value in (("command", command), ("workingDirectory", "$PROJECT_DIR$"),
                       ("channel", "DEFAULT"), ("allFeatures", "false"),
                       ("emulateTerminal", "false"), ("withSudo", "false")):
        option(config, key, value)
    ET.SubElement(ET.SubElement(config, "envs"), "env", name="RUST_BACKTRACE", value="1")
    ET.SubElement(config, "method", v="2")
    return xml(project)


def project_files(root: Path, paths: list[str] | None = None) -> dict[str, str]:
    roots, cargo = source_model(root, tracked_paths(root) if paths is None else paths)
    names = [module_name(path) for path in roots]
    if len(names) != len(set(names)):
        raise ValueError("colliding IntelliJ module names")
    files = {f".idea/modules/{module_name(path)}.iml": module_file(path) for path in roots}
    project, manager = component("ProjectModuleManager")
    modules = ET.SubElement(manager, "modules")
    for path in roots:
        file = "$PROJECT_DIR$/.idea/modules/" + module_name(path) + ".iml"
        ET.SubElement(modules, "module", fileurl="file://" + file, filepath=file,
                      **({"group": "LSF/" + path.split("/")[0]} if path != "." else {}))
    files[".idea/modules.xml"] = xml(project)
    project, manager = component("CargoProjects")
    for manifest in cargo:
        ET.SubElement(manager, "cargoProject", FILE="$PROJECT_DIR$/" + manifest)
    project_sdk = ET.SubElement(project, "component", name="ProjectRootManager", version="2", languageLevel="JDK_25")
    ET.SubElement(project_sdk, "output", url="file://$PROJECT_DIR$/target/idea-classes")
    files[".idea/misc.xml"] = xml(project)
    project, manager = component("Encoding")
    ET.SubElement(manager, "file", url="PROJECT", charset="UTF-8")
    files[".idea/encodings.xml"] = xml(project)
    project, manager = component("VcsDirectoryMappings")
    ET.SubElement(manager, "mapping", directory="$PROJECT_DIR$", vcs="Git")
    files[".idea/vcs.xml"] = xml(project)
    project, manager = component("ExternalDependencies")
    # Plugin descriptor IDs, not implementation packages (com.intellij.sh).
    # Shell Script is bundled with IDEA; a disabled plugin should be enabled.
    for plugin in ("com.jetbrains.rust", "com.jetbrains.sh"):
        ET.SubElement(manager, "plugin", id=plugin)
    files[".idea/externalDependencies.xml"] = xml(project)
    for task, folder in MAKE_TASKS.items():
        files[f".run/LSF-{task}.run.xml"] = run_configuration(task, folder)
    for task, (folder, _) in EXTRA_TASKS.items():
        files[f".run/LSF-{task}.run.xml"] = run_configuration(task, folder)
    windows_tasks = intellij_windows.TASKS | (EXTRA_TASKS.keys() - {"ide-node-prepare"})
    for task in sorted(windows_tasks):
        folder = MAKE_TASKS[task] if task in MAKE_TASKS else EXTRA_TASKS[task][0]
        files[f".run/LSF-{task}-windows.run.xml"] = run_configuration(task, folder, windows=True)
    for package in ("latent", "latentd", "latent-control"):
        name = package + "-help"
        files[f".run/LSF-{name}.run.xml"] = cargo_configuration(name, f"run --package {package} --locked -- --help")
    files[".run/LSF-core-unit-tests.run.xml"] = cargo_configuration("core-unit-tests", "test --package latent-core --lib --locked")
    files[".run/LSF-local-node.run.xml"] = cargo_configuration(
        "local-node", "run --package latentd --locked -- serve --config target/ide/node/node.json")
    return files


def owned_files(root: Path) -> set[str]:
    for directory in (root / ".idea", root / ".idea/modules", root / ".run"):
        if directory.is_symlink():
            raise ValueError("refusing symlinked IDE directory")
    files = []
    for pattern in (".idea/*.xml", ".idea/modules/lsf*.iml", ".run/LSF-*.run.xml"):
        files.extend(root.glob(pattern))
    return {path.relative_to(root).as_posix() for path in files
            if not path.is_symlink() and path.is_file() and MARKER in path.read_text(encoding="utf-8")}


def write_files(root: Path, files: dict[str, str]) -> None:
    # Validate every destination before changing anything; never follow a local
    # .idea/ or .run/ symlink out of the checkout or overwrite an unowned config.
    for name in files.keys() | owned_files(root):
        path = root
        for part in PurePosixPath(safe_relative(name)).parts:
            path /= part
            if path.is_symlink():
                raise ValueError(f"refusing symlink destination: {name}")
        if path.exists() and MARKER not in path.read_text(encoding="utf-8"):
            raise ValueError(f"unowned IDE file; back it up before regenerating: {name}")
    for name in owned_files(root) - files.keys():
        (root / name).unlink()
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


def check_files(root: Path, files: dict[str, str]) -> list[str]:
    changed = sorted(name for name, text in files.items()
                     if not (root / name).is_file() or (root / name).read_bytes() != text.encode("utf-8"))
    return sorted(set(changed) | (owned_files(root) - files.keys()))


def task_command(root: Path, task: str) -> list[str]:
    if task in MAKE_TASKS:
        command = ["make", task, "PYTHON=" + shlex.quote(sys.executable)]
        if task == "validate":
            command.append("WORKSPACE_ROOT=target/ide/validate-" + uuid.uuid4().hex)
        return command
    if task in EXTRA_TASKS:
        return [sys.executable, *EXTRA_TASKS[task][1]]
    raise ValueError(f"unknown IDE task: {task}")


def prepare_node(root: Path) -> None:
    """Explicit trusted-local quickstart state; no listener or process is started."""
    if not sys.platform.startswith("linux"):
        raise ValueError("the native local node requires Linux/WSL or a Linux backend")
    destination = root
    for part in ("target", "ide"):
        destination /= part
        if destination.is_symlink():
            raise ValueError("refusing symlinked local-node destination")
        destination.mkdir(mode=0o700, exist_ok=True)
    destination /= "node"
    # Exclusive ownership: never reset existing state or replace credentials.
    destination.mkdir(mode=0o700, exist_ok=False)
    token = secrets.token_urlsafe(32)
    node = {
        "formatVersion": 1, "dataDirectory": "data", "bind": "127.0.0.1:43170",
        "nodeId": "intellij-local", "execution": {"maximumWallTimeMillis": 5000},
        "credentials": [{"token": token, "subject": "intellij-operator",
                         "tenant": "examples", "role": "operator"}],
    }
    client = {"formatVersion": 1, "defaultProfile": "local", "profiles": [{
        "name": "local", "endpoint": "http://127.0.0.1:43170", "tenant": "examples",
        "token": token, "connectTimeoutMillis": 2000, "rpcTimeoutMillis": 5000,
    }]}
    for name, document in (("node.json", node), ("client.json", client)):
        descriptor = os.open(destination / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as output:
            json.dump(document, output, indent=2)
            output.write("\n")
    print("Prepared private target/ide/node files; no node was started.")
    print("Run/Debug LSF - local-node. Keep target/ide/node for restart; never commit its credentials.")


def doctor(root: Path) -> int:
    missing = []
    tools = ("git",) if sys.platform == "win32" else ("git", "bash", "make", "cargo", "rustup")
    for tool in tools:
        present = shutil.which(tool) is not None
        print(f"{tool}: {'available' if present else 'missing'}")
        if not present:
            missing.append(tool)
    if sys.platform == "win32":
        print("Windows configurations use intellij.cmd; Bash, Make and WSL are not prerequisites.")
        for tool in ("node", "cargo", "rustup"):
            print(f"{tool}: {'available' if shutil.which(tool) else 'missing'} (task-specific)")
    print(f"Python: {sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}")
    print("Project pins: rust-toolchain.toml, tools/toolchain.toml, website/package.json")
    print("Java SDK: select the pinned JDK as the project SDK; run java-client-prepare explicitly.")
    print("IDE plugins and local SDK selections cannot be verified outside the IDE.")
    print("Native runtime/full validation: use Linux/WSL or a Linux remote-development backend.")
    print("See docs/development/intellij-idea.md for first-open and platform checks.")
    drift = check_files(root, project_files(root))
    for name in drift:
        print("IDE metadata drift: " + name)
    return 1 if missing or drift else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_mutually_exclusive_group()
    commands.add_argument("--check", action="store_true", help="read-only drift check")
    commands.add_argument("--write", action="store_true", help="explicitly regenerate owned project files")
    commands.add_argument("--export", type=Path, help="write a review proposal to a NEW directory")
    parser.add_argument("action", nargs="?", choices=("doctor", "run", "node-prepare", "website-start"))
    parser.add_argument("task", nargs="?")
    args = parser.parse_args(argv)
    try:
        if args.action and (args.check or args.write or args.export):
            parser.error("choose generation or an action, not both")
        if args.action == "run":
            if not args.task:
                parser.error("run requires a task")
            if sys.platform == "win32" and (args.task in MAKE_TASKS or args.task == "website-start"):
                return intellij_windows.run(ROOT, args.task)
            command = task_command(ROOT, args.task)
            print("LSF IDE task: " + args.task, flush=True)
            return subprocess.run(command, cwd=ROOT, check=False).returncode
        if args.task:
            parser.error("task is only valid after run")
        if args.action == "doctor":
            return doctor(ROOT)
        if args.action == "node-prepare":
            prepare_node(ROOT)
            return 0
        if args.action == "website-start":
            if sys.platform == "win32":
                return intellij_windows.run(ROOT, "website-start")
            subprocess.run(["node", "website/scripts/check-package-manager.mjs"], cwd=ROOT, check=True)
            return subprocess.run(["node", "website/toolchain/node_modules/npm/bin/npm-cli.js",
                                   "--prefix", "website", "start"], cwd=ROOT, check=False).returncode
        files = project_files(ROOT)
        if args.export:
            args.export.mkdir(parents=True, exist_ok=False)
            write_files(args.export, files)
            print(f"Exported {len(files)} IDE files for review.")
            return 0
        if args.write:
            write_files(ROOT, files)
            print(f"Wrote {len(files)} IDE files. Review git diff before committing.")
            return 0
        changed = check_files(ROOT, files)
        if changed:
            print("IntelliJ metadata needs review; run python3 tools/intellij.py --write:")
            print("\n".join(changed))
            return 1
        print(f"IntelliJ metadata is current ({len(files)} files).")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError, subprocess.TimeoutExpired) as error:
        print(f"IntelliJ setup: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
