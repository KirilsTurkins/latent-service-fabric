// Compiler-private opt-in. A future owned module selects exact generated
// bindings here; application configuration cannot provide names or record ids.
export const selectedBorrowReleaseImports = Object.freeze([]);

export function borrowReleaseHandoff(source, parse, selected = selectedBorrowReleaseImports) {
  const fail = () => { throw new Error('selected-runtime-borrow-handoff-shape-drift'); };
  if (!Array.isArray(selected) || selected.length > 16) fail();
  if (!selected.length) return source; // Preserve default generated bytes exactly.
  if (source.includes('__lsfBorrow')) fail();
  const identifier = (node, name) => node?.type === 'Identifier' && node.name === name;
  const member = (node, name) => node?.type === 'MemberExpression' && !node.computed &&
    identifier(node.object, '__lsfImports') && identifier(node.property, name);
  const names = new Set(), aliases = new Set();
  for (const row of selected) {
    if (!row || Object.keys(row).sort().join(',') !== 'alias,binding' ||
        typeof row.binding !== 'string' || typeof row.alias !== 'string' ||
        !/^[A-Za-z_$][\w$]*$/.test(row.binding) || !/^[A-Za-z_$][\w$]*$/.test(row.alias) ||
        names.has(row.binding) || aliases.has(row.alias)) fail();
    names.add(row.binding); aliases.add(row.alias);
  }
  let tree;
  try { tree = parse(source, {ecmaVersion: 'latest', sourceType: 'module'}); }
  catch { fail(); }
  const entries = [];
  function walk(node, parents = []) {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) { for (const child of node) walk(child, parents); return; }
    if (typeof node.type !== 'string') return;
    entries.push({node, parents});
    for (const value of Object.values(node)) {
      if (value && typeof value === 'object') walk(value, [...parents, node]);
    }
  }
  walk(tree);
  const bridges = entries.filter(({node}) => node.type === 'VariableDeclarator' && identifier(node.id, '__lsfImports'));
  if (bridges.length !== 1) fail();
  const {node: bridge, parents: bridgeParents} = bridges[0];
  const declaration = bridgeParents.at(-1);
  if (bridgeParents.length !== 2 || bridgeParents[0] !== tree ||
      declaration?.type !== 'VariableDeclaration' || declaration.kind !== 'const' || declaration.declarations.length !== 1 ||
      bridge.init?.type !== 'MemberExpression' || bridge.init.computed ||
      !identifier(bridge.init.object, 'contentGlobal') || !identifier(bridge.init.property, '__lsfAsyncImportBridge')) fail();
  const edits = [];
  for (const {binding} of selected) {
    const candidates = entries.filter(({node}) => node.type === 'FunctionDeclaration' && identifier(node.id, binding));
    if (candidates.length !== 1) fail();
    const {node: fn, parents} = candidates[0];
    const [reservation, helper, body] = fn.body?.body ?? [];
    if (parents.length !== 1 || parents[0] !== tree || !fn.async || fn.generator ||
        fn.body.body.length !== 3 || fn.params.some(p => p.type !== 'Identifier') ||
        reservation?.type !== 'VariableDeclaration' || reservation.kind !== 'const' ||
        reservation.declarations.length !== 1 || !identifier(reservation.declarations[0].id, '__lsfImportId') ||
        helper?.type !== 'VariableDeclaration' || helper.kind !== 'const' || helper.declarations.length !== 1 ||
        !identifier(helper.declarations[0].id, '__lsfAwaitImport') ||
        helper.declarations[0].init?.type !== 'ArrowFunctionExpression' || helper.declarations[0].init.async ||
        body?.type !== 'TryStatement' || body.handler || body.finalizer?.body.length !== 1) fail();
    const reserve = reservation.declarations[0].init;
    const carrier = helper.declarations[0].init;
    const native = carrier.body;
    const finish = body.finalizer.body[0];
    if (reserve?.type !== 'CallExpression' || !member(reserve.callee, 'reserve') || reserve.arguments.length < 3 ||
        reserve.arguments.slice(0, 3).some(p => p.type !== 'Literal' || !Number.isSafeInteger(p.value) || p.value < 0) ||
        reserve.arguments.slice(3).some(p => p.type !== 'Identifier' || !fn.params.some(a => a.name === p.name)) ||
        finish.type !== 'ExpressionStatement' || finish.expression?.type !== 'CallExpression' ||
        !member(finish.expression.callee, 'finish') || finish.expression.arguments.length !== 1 ||
        !identifier(finish.expression.arguments[0], '__lsfImportId') ||
        carrier.params.length !== 1 || carrier.params[0].type !== 'RestElement' ||
        !identifier(carrier.params[0].argument, 'lowered') ||
        native.type !== 'CallExpression' || !identifier(native.callee, '$' + binding) ||
        native.arguments.length !== 2 || native.arguments[0].type !== 'BinaryExpression' ||
        native.arguments[0].operator !== '|' || !identifier(native.arguments[0].left, '__lsfImportId') ||
        native.arguments[0].right.type !== 'Literal' || native.arguments[0].right.value !== 0 ||
        native.arguments[1].type !== 'SpreadElement' || !identifier(native.arguments[1].argument, 'lowered')) fail();
    const inside = entries.filter(({node}) => node.start >= fn.start && node.end <= fn.end);
    if (inside.filter(({node}) => node.type === 'CallExpression' && member(node.callee, 'reserve')).length !== 1 ||
        inside.filter(({node}) => node.type === 'CallExpression' && member(node.callee, 'finish')).length !== 1 ||
        inside.some(({node}) => node.type === 'AwaitExpression' && node.start < body.start)) fail();
    edits.push({start: body.block.start + 1, end: body.block.start + 1,
      text: `\n  __lsfBorrowArm(${binding}, __lsfImportId);`});
  }
  const helper = `
// This frame exists only during the synchronous reservation prefix. It cannot
// outlive an await, select another binding, or carry an ambient caller id.
let __lsfBorrowFrame = null;
function __lsfBorrowArm(original, id) {
  const frame = __lsfBorrowFrame;
  if (!frame || frame.original !== original) return;
  if (frame.handle !== null) throw new Error('selected-runtime-borrow-handoff-duplicate');
  frame.handle = __lsfImports.watchBorrow(id);
}
function __lsfBorrowStart(original, receiver, args) {
  const frame = {original, handle: null};
  const previous = __lsfBorrowFrame;
  let result;
  __lsfBorrowFrame = frame;
  try { result = Reflect.apply(original, receiver, args); }
  finally { __lsfBorrowFrame = previous; }
  const handle = frame.handle;
  const requireHandle = () => {
    if (handle === null) throw new Error('selected-runtime-borrow-handoff-not-admitted');
    return handle;
  };
  // Preserve the original logical result/rejection separately. Failed native
  // admission leaves that rejection visible and cannot yield a release proof.
  return Object.freeze({
    promise: contentGlobal.Promise.resolve(result),
    get borrowReleased() {
      return contentGlobal.Promise.resolve(__lsfImports.borrowReleased(requireHandle()));
    },
    cancel() {
      return contentGlobal.Promise.resolve(__lsfImports.cancelBorrow(requireHandle()));
    }
  });
}
const __lsfBorrowCalls = Object.freeze({
${selected.map(({alias, binding}) => `  [${JSON.stringify(alias)}](...args) { return __lsfBorrowStart(${binding}, this, args); }`).join(',\n')}
});
`;
  edits.push({start: declaration.end, end: declaration.end, text: helper});
  edits.sort((a, b) => b.start - a.start);
  let previous = source.length;
  for (const edit of edits) {
    if (edit.end > previous) fail();
    source = source.slice(0, edit.start) + edit.text + source.slice(edit.end);
    previous = edit.start;
  }
  try { parse(source, {ecmaVersion: 'latest', sourceType: 'module'}); }
  catch { fail(); }
  return source;
}
